const { PrismaClient } = require('@prisma/client');
const bcrypt = require('bcrypt');

const prisma = new PrismaClient();

const USERS_TO_CREATE = 50;
const POSTS_TO_CREATE = 30;
const REPLIES_TO_CREATE = 20;
const LIKES_TO_CREATE = 50;

const postContents = [
    "Just deployed my new app! 🚀 #coding #webdev",
    "Does anyone else feel like they spend 90% of their time debugging? 😅",
    "Coffee is the most important meal of the day. Change my mind. ☕️",
    "Learning Rust. It's... interesting. 🦀",
    "Why is it that code works perfectly until you show it to someone? 🤔",
    "Open source is the future of software development.",
    "Designing a new UI system today. Love getting creative! 🎨",
    "Just read an amazing article about system architecture.",
    "Remote work life: business on top, pajamas on bottom. 🏠",
    "React 19 looks promising! Can't wait to try the new features.",
    "Python is great for scripting, but give me TS for large apps any day.",
    "Currently reading 'Clean Code'. A must-read for every dev.",
    "Who's going to the tech meetup next week?",
    "Optimization is key. Shaved 200ms off our load time! ⚡️",
    "Imposter syndrome hitting hard today, but we keep pushing.",
    "Building in public is scary but rewarding.",
    "Tailwind CSS has completely changed how I write styles.",
    "Remember to hydrate! 💧",
    "Just updated my portfolio. Check it out!",
    "Weekend project: building a custom mechanical keyboard. ⌨️"
];

const replyContents = [
    "Totally agree with you!",
    "This is awesome! 🔥",
    "Valid point.",
    "Have you tried using a different approach?",
    "Congratulations! 🎉",
    "I was just thinking the same thing.",
    "Can you share more details?",
    "Interesting perspective.",
    "Keep up the great work! 💪",
    "Lol, so true! 😂"
];

async function main() {
    console.log('🌱 Starting dummy data seeding...');

    // 1. Ensure we have enough users
    // 1. Ensure we have enough users
    let users = await prisma.user.findMany();

    // Ensure a fixed demo user exists for easy login
    const specificUsers = [
        { email: 'demo@xclone.com', name: 'Demo User', handle: 'demo_user' },
        { email: 'ashishrangavkar01@gmail.com', name: 'Ashish Rangavkar', handle: 'ashish01' },
        { email: 'john@example.com', name: 'John Doe', handle: 'johndoe' }
    ];

    for (const u of specificUsers) {
        const existing = await prisma.user.findUnique({ where: { email: u.email } });
        if (!existing) {
            await prisma.user.create({
                data: {
                    email: u.email,
                    passwordHash: await bcrypt.hash('password123', 10),
                    profile: {
                        create: {
                            name: u.name,
                            handle: u.handle,
                            bio: 'Fixed account for testing.'

                        }
                    }
                }
            });
            console.log(`✅ Created specific user: ${u.email}`);
        }
    }

    // Refresh users list
    users = await prisma.user.findMany();

    if (users.length < USERS_TO_CREATE) {
        console.log(`Creating ${USERS_TO_CREATE - users.length} more users...`);
        const password = await bcrypt.hash('password123', 10);

        for (let i = 0; i < (USERS_TO_CREATE - users.length); i++) {
            const userNum = users.length + i + 1;

            // Use stable email format matching userpassword.md
            const email = `user${userNum}@xclone.com`;

            // Check if exists first (to avoid unique constraint errors if partial seed exists)
            const existing = await prisma.user.findUnique({ where: { email } });

            if (!existing) {
                await prisma.user.create({
                    data: {
                        email: email,
                        passwordHash: password,
                        profile: {
                            create: {
                                name: `User ${userNum}`,
                                handle: `user${userNum}`,
                                bio: 'Just another dummy user generated by the seed script.',
                            }
                        }
                    }
                });
            }
        }
        users = await prisma.user.findMany();
    }

    console.log(`✅ Using ${users.length} users for interactions.`);

    // 2. Create Posts
    const posts = [];
    console.log(`Creating ${POSTS_TO_CREATE} posts (50% images, 50% charts)...`);

    // Helper to generate random chart URL
    function generateChartUrl() {
        const types = ['bar', 'line', 'pie', 'doughnut', 'radar'];
        const type = types[Math.floor(Math.random() * types.length)];
        const dataPoints = Array.from({ length: 5 }, () => Math.floor(Math.random() * 100));

        const config = {
            type: type,
            data: {
                labels: ['Jan', 'Feb', 'Mar', 'Apr', 'May'],
                datasets: [{
                    label: 'Data',
                    data: dataPoints,
                    backgroundColor: 'rgba(54, 162, 235, 0.5)',
                    borderColor: 'rgb(54, 162, 235)',
                    borderWidth: 1
                }]
            },
            options: {
                title: {
                    display: true,
                    text: `Random ${type.charAt(0).toUpperCase() + type.slice(1)} Chart`
                }
            }
        };

        return `https://quickchart.io/chart?c=${encodeURIComponent(JSON.stringify(config))}`;
    }

    for (let i = 0; i < POSTS_TO_CREATE; i++) {
        const randomUser = users[Math.floor(Math.random() * users.length)];
        const content = postContents[Math.floor(Math.random() * postContents.length)];

        // Random date within last 1 hour to ensure they show up on top
        const createdAt = new Date(Date.now() - Math.floor(Math.random() * 60 * 60 * 1000));

        let mediaUrls = [];

        // 50% chance for generic image, 50% for chart
        if (Math.random() > 0.5) {
            const width = 600 + Math.floor(Math.random() * 200);
            const height = 400 + Math.floor(Math.random() * 200);
            mediaUrls.push(`https://picsum.photos/${width}/${height}?random=${Math.random()}`);
        } else {
            mediaUrls.push(generateChartUrl());
        }

        const post = await prisma.post.create({
            data: {
                userId: randomUser.id,
                content: content,
                mediaUrls: JSON.stringify(mediaUrls),
                createdAt: createdAt
            }
        });
        posts.push(post);
    }
    console.log(`✅ Created ${posts.length} posts (some with media).`);

    // 3. Create Replies
    console.log(`Creating ${REPLIES_TO_CREATE} replies...`);
    for (let i = 0; i < REPLIES_TO_CREATE; i++) {
        const randomUser = users[Math.floor(Math.random() * users.length)];
        const randomPost = posts[Math.floor(Math.random() * posts.length)];
        const content = replyContents[Math.floor(Math.random() * replyContents.length)];

        // Reply created after the post
        const postTime = new Date(randomPost.createdAt).getTime();
        const now = Date.now();
        const replyTime = new Date(postTime + Math.random() * (now - postTime));

        await prisma.post.create({
            data: {
                userId: randomUser.id,
                content: content,
                replyToId: randomPost.id,
                createdAt: replyTime
            }
        });
    }
    console.log(`✅ Created ${REPLIES_TO_CREATE} replies.`);

    // 4. Create Likes
    console.log(`Creating ${LIKES_TO_CREATE} likes...`);
    let likesCreated = 0;

    // Refresh posts list to include replies if we want to like replies too
    const allPosts = await prisma.post.findMany({ select: { id: true } });

    for (let i = 0; i < LIKES_TO_CREATE; i++) {
        const randomUser = users[Math.floor(Math.random() * users.length)];
        const randomPost = allPosts[Math.floor(Math.random() * allPosts.length)];

        try {
            await prisma.like.create({
                data: {
                    userId: randomUser.id,
                    postId: randomPost.id
                }
            });
            likesCreated++;
        } catch (e) {
            // Ignore unique constraint violations (user already liked post)
            if (e.code !== 'P2002') console.error('Error creating like:', e.message);
        }
    }
    console.log(`✅ Created ${likesCreated} likes.`);

    // 5. Create some follows
    console.log('Creating follow relationships...');
    for (let i = 0; i < 20; i++) {
        const follower = users[Math.floor(Math.random() * users.length)];
        const following = users[Math.floor(Math.random() * users.length)];

        if (follower.id !== following.id) {
            try {
                await prisma.follow.create({
                    data: {
                        followerId: follower.id,
                        followingId: following.id
                    }
                });
            } catch (e) {
                // Ignore duplicates
            }
        }
    }
    console.log('✅ Created follow relationships.');

    // 6. Create Chats with Charts
    console.log('Starting chat seeding...');

    // Helper to generate random chart URL
    function generateChartUrl() {
        const types = ['bar', 'line', 'pie', 'doughnut', 'radar'];
        const type = types[Math.floor(Math.random() * types.length)];
        const dataPoints = Array.from({ length: 5 }, () => Math.floor(Math.random() * 100));

        const config = {
            type: type,
            data: {
                labels: ['Q1', 'Q2', 'Q3', 'Q4', 'Q5'],
                datasets: [{
                    label: 'Sales',
                    data: dataPoints,
                    backgroundColor: 'rgba(75, 192, 192, 0.5)',
                    borderColor: 'rgb(75, 192, 192)',
                    borderWidth: 1
                }]
            },
            options: {
                title: { display: true, text: `Quarterly ${type} Report` }
            }
        };
        return `https://quickchart.io/chart?c=${encodeURIComponent(JSON.stringify(config))}`;
    }

    // Use ALL users to ensure everyone has charts
    const usersWithChats = users;
    console.log(`Seeding chats for ${usersWithChats.length} users...`);

    for (const currentUser of usersWithChats) {
        // Create a conversation with another random user
        const otherUser = users.find(u => u.id !== currentUser.id && Math.random() > 0.5) || users[users.length - 1];
        if (otherUser.id === currentUser.id) continue;

        const conversation = await prisma.conversation.create({
            data: {
                type: 'direct',
                participants: {
                    create: [
                        { userId: currentUser.id },
                        { userId: otherUser.id }
                    ]
                }
            }
        });

        // Create 15 messages (reduced count per user to save time, but ensuring charts)
        const messages = [];
        for (let m = 0; m < 15; m++) {
            const senderId = Math.random() > 0.5 ? currentUser.id : otherUser.id;
            let content = '';

            // High probability of chart (70%) to satisfy "add some chart" request
            if (Math.random() > 0.3) {
                content = generateChartUrl();
            } else {
                content = `Hey, check out this data! Message ${m + 1}`;
            }

            messages.push({
                conversationId: conversation.id,
                senderId: senderId,
                content: content,
                createdAt: new Date(Date.now() - (15 - m) * 60000)
            });
        }
        await prisma.message.createMany({ data: messages });
    }
    console.log('✅ Chat seeding complete for ALL users.');

    console.log('\n🎉 Seed complete!');
}

main()
    .catch((e) => {
        console.error(e);
        process.exit(1);
    })
    .finally(async () => {
        await prisma.$disconnect();
    });
